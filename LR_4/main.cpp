#include <iostream>  // Для стандартного ввода и вывода (std::cin, std::cout)
#include <windows.h> // Для настройки кодировки консоли в Windows
#include <string>    // Для работы со строками (std::string)
#include <iomanip>   // Для манипуляторов ввода/вывода (например, std::hex, std::oct)
#include <sstream>   // Для работы со строковыми потоками (std::stringstream)
#include <bitset>    // Для перевода чисел в двоичную систему (std::bitset)

int main() {
    // Установка кодировки UTF-8 для корректного отображения русского языка в консоли
    SetConsoleOutputCP(CP_UTF8);
    SetConsoleCP(CP_UTF8);

    int program;     // Переменная для хранения номера выбранного пункта меню

    int number;      // Переменная для числовой оценки или промежуточной проверки числа
    int system;      // Переменная для хранения основания системы счисления (2, 8, 10, 16)
    char letter;     // Переменная для буквенной оценки (A-F)
    std::string string; // Строка для ввода числа в калькуляторе систем счисления

    // Вывод главного меню на экран
    std::cout << "Список программ:" << std::endl;
    std::cout << "1. Перевод оценок (1-5) в словесный формат" << std::endl;
    std::cout << "2. Перевод оценок (A-F) в словесный формат" << std::endl;
    std::cout << "3. Калькулятор систем счисления" << std::endl;
    std::cout << "0. Выйти из программы" << std::endl;
    std::cout << "Выберите программу: ";

    // Считывание выбора пользователя
    std::cin >> program;

    // Проверка корректности ввода: введено ли число от 0 до 3 и нет ли лишних символов в строке
    while (std::cin.fail() || program < 0 || program > 3 || std::cin.get() != '\n') {
        std::cin.clear();               // Сброс флагов ошибок потока ввода
        std::cin.ignore(10000, '\n');   // Очистка буфера ввода до символа новой строки
        std::cout << "Ошибка ввода программы!" << std::endl;
        std::cout << "Выберите программу: ";
        std::cin >> program;            // Повторная попытка ввода
    }

    // Обработка выбранного пункта меню
    switch (program) {
        // Пункт 1: Перевод числовой оценки (1-5) в словесный формат
        case 1: {
            std::cout << "Введите оценку:";
            std::cin >> number;

            // Сопоставление введенного числа с текстовым описанием оценки
            switch (number) {
                case 1: std::cout << "Оценка " << number << "-<<Плохо>>" << std::endl; break;
                case 2: std::cout << "Оценка " << number << "-<<Неудовлетворительно>>" << std::endl; break;
                case 3: std::cout << "Оценка " << number << "-<<Удовлетворительно>>" << std::endl; break;
                case 4: std::cout << "Оценка " << number << "-<<Хорошо>>" << std::endl; break;
                case 5: std::cout << "Оценка " << number << "-<<Отлично>>" << std::endl; break;
                default: std::cout << "Введена не оценка!" << std::endl; // Если число вне диапазона 1-5
            }
            break;
        }

        // Пункт 2: Перевод буквенной оценки (A-F) в словесный формат
        case 2: {
            std::cout << "Введите оценку:";
            std::cin >> letter;

            // Сопоставление введенной буквы с текстовым описанием оценки
            switch (letter) {
                case 'F': std::cout << "Оценка " << letter << "-<<Плохо>>" << std::endl; break;
                case 'D': std::cout << "Оценка " << letter << "-<<Неудовлетворительно>>" << std::endl; break;
                case 'C': std::cout << "Оценка " << letter << "-<<Удовлетворительно>>" << std::endl; break;
                case 'B': std::cout << "Оценка " << letter << "-<<Хорошо>>" << std::endl; break;
                case 'A': std::cout << "Оценка " << letter << "-<<Отлично>>" << std::endl; break;
                default: std::cout << "Введена не оценка!" << std::endl; // Если введена другая буква или символ
            }
            break;
        }

        // Пункт 3: Калькулятор систем счисления
        case 3: {
            std::cout << "Введите число от 0 до 255: ";
            std::cin >> string; // Считывание числа в виде строки

            // Преобразование строки в число для первичной проверки диапазона
            std::stringstream(string) >> number;

            // Проверка: входит ли число в диапазон 0-255 и нет ли ошибок в потоке ввода
            if ( number < 0 || number > 255 || std::cin.fail() || std::cin.get() != '\n') {
                std::cout << "Неправильно введено число!";
                break; // Выход из case 3 при ошибке
            }

            std::cout << "Введите систему счисления: ";
            std::cin >> system; // Считывание исходной системы счисления

            long dec; // Переменная для хранения числа, переведенного в десятичную систему

            // Блок перехвата исключений (на случай ошибки в std::bitset, если введены не 0 и 1)
            try {
                // Перевод введенной строки в десятичное число (dec) в зависимости от исходной системы
                switch (system) {
                    case 2: dec = std::bitset<8>(string).to_ulong(); break; // Из 2-ичной в 10-ичную
                    case 8: std::stringstream(string) >> std::oct >> dec; break; // Из 8-ичной в 10-ичную
                    case 10: std::stringstream(string) >> dec; break; // Из 10-ичной в 10-ичную
                    case 16: std::stringstream(string) >> std::hex >> dec; break; // Из 16-ичной в 10-ичную
                    default: std:: cout << "Ошибка ввода системы счисления!";
                }
            } catch (std::exception& e) {
                // Обработка ошибки, если строка не соответствует формату (например, для bitset)
                std::cout << "Неправильно введено число!" << std::endl;
                break;
            }

            // Вывод полученного числа во всех четырех системах счисления
            std::cout << "10-ичная: " << dec << std::endl;
            std::cout << "16-ичная: " << std::hex << dec << std::endl;          // Вывод в шестнадцатеричном формате
            std::cout << "8-ичная:  " << std::oct << dec << std::endl;          // Вывод в восьмеричном формате
            std::cout << "2-ичная:  " << std::bitset<8>(dec) << std::endl;      // Вывод в двоичном формате (8 бит)
        }

    }

    return 0; // Успешное завершение программы
}